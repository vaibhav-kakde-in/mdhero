#!/usr/bin/env node
/**
 * Builds the self-contained preview.html used by the macOS Quick Look extension.
 *
 * Three steps:
 *   1. Extract MarkdownRenderer.svelte's <style> block and de-scope it, so the
 *      preview inherits the app's document styling from a single source rather
 *      than a copy that quietly drifts.
 *   2. Run Vite (vite.quicklook.config.ts) to produce one JS bundle + one CSS file.
 *   3. Inline both into one HTML file with a nonce-based CSP.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const COMPONENT = path.join(ROOT, "src/lib/components/MarkdownRenderer.svelte");
const GENERATED = path.join(ROOT, "src/quicklook/component-styles.generated.css");
const OUT_DIR = path.join(ROOT, "build-quicklook");

/**
 * Svelte's `:global(X)` wrappers are compile-time scoping hints, meaningless in
 * a plain stylesheet. Unwrap them, honouring nested parens so selectors like
 * `:global(:not(pre) > code)` survive intact.
 *
 * @param {string} css
 * @returns {string}
 */
export function stripGlobal(css) {
  let out = "";
  for (let i = 0; i < css.length; ) {
    const at = css.indexOf(":global(", i);
    if (at === -1) {
      out += css.slice(i);
      break;
    }
    out += css.slice(i, at);
    let depth = 1;
    let j = at + ":global(".length;
    for (; j < css.length && depth > 0; j++) {
      if (css[j] === "(") depth++;
      else if (css[j] === ")") depth--;
    }
    out += css.slice(at + ":global(".length, j - 1);
    i = j;
  }
  return out;
}

function extractComponentStyles() {
  const src = fs.readFileSync(COMPONENT, "utf8");
  const open = src.lastIndexOf("<style>");
  const close = src.lastIndexOf("</style>");
  if (open === -1 || close === -1 || close < open) {
    throw new Error("could not find a <style> block in MarkdownRenderer.svelte");
  }
  const css = src.slice(open + "<style>".length, close);
  const header =
    "/* GENERATED by scripts/build-quicklook.mjs from\n" +
    " * src/lib/components/MarkdownRenderer.svelte — do not edit by hand.\n" +
    " * Edit the component; this file is rewritten on every build. */\n";
  fs.writeFileSync(GENERATED, header + stripGlobal(css));
  return css.length;
}

/**
 * Makes a JS bundle safe to embed in a classic inline <script>.
 *
 * `<!--` opens an HTML-like comment there and `</script` closes the element
 * early. Minified bundles carry both inside string and regex literals —
 * DOMPurify has "<!-->" and markdown-it has /<!--(?:-?>|...)/ — and either one
 * silently destroys the whole bundle: the script fails to PARSE, so nothing is
 * defined and a try/catch around it never runs.
 *
 * The `<` is escaped as \x3C, which is valid in string literals, template
 * literals and regex literals alike. `<\!--` is not — `\!` is an identity
 * escape that a unicode-mode regex rejects.
 *
 * @param {string} js
 * @returns {string}
 */
export function escapeForInlineScript(js) {
  return js.replace(/<!--/g, "\\x3C!--").replace(/<\/script/gi, "\\x3C/script");
}

function buildHtml() {
  const rawJs = fs.readFileSync(path.join(OUT_DIR, "preview.js"), "utf8");
  const css = fs.readFileSync(path.join(OUT_DIR, "preview.css"), "utf8");

  const js = escapeForInlineScript(rawJs);
  if (/<\/style/i.test(css)) throw new Error("stylesheet would close its own <style> element");

  // #security: the extension holds com.apple.security.network.client (WKWebView
  // will not load without it), so this policy is the only thing standing between
  // a hostile document and the network.
  //   - script-src is nonce-based, NOT 'unsafe-inline': the extension mints a
  //     fresh nonce per preview, so even a script that survived DOMPurify cannot
  //     execute. 'unsafe-eval' is required by KaTeX/Mermaid codegen.
  //   - connect-src 'none' — nothing may phone home.
  //   - img-src excludes https: ON PURPOSE. The app allows remote images; here
  //     a remote fetch would be a working exfiltration channel out of an
  //     extension that cannot be watched. Remote images therefore do not render
  //     in Quick Look. Flip this only as a deliberate, documented decision.
  const csp = [
    "default-src 'none'",
    "script-src 'nonce-__CSP_NONCE__' 'unsafe-eval'",
    "style-src 'unsafe-inline'",
    "img-src data:",
    "font-src data:",
    "connect-src 'none'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");

  /*
   * Two substitution points for the extension, both unique tokens rather than
   * `</head>` / `</body>`:
   *
   *   __MDHERO_PRELUDE__  error bridge, installed before the renderer runs
   *   __MDHERO_BOOT__     the call that hands over the document text
   *
   * They are tokens for a reason. The bundle's own minified source contains the
   * literal strings "</head>" and "</body>" (DOMPurify builds document
   * fragments), so substituting at those injects a <script> — and therefore a
   * </script> — INSIDE the bundle. That truncates it mid-file and spills the
   * remainder onto the page as visible text, which is exactly the failure this
   * cost a long afternoon to find.
   */
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${csp}">
__MDHERO_PRELUDE__
<title>MDHero preview</title>
<style>${css}</style>
</head>
<body>
<article id="doc" class="md-content prose prose-slate dark:prose-invert max-w-none mx-auto px-8 py-8"></article>
<script nonce="__CSP_NONCE__">try{${js}}catch(e){__mdheroReport("renderer bundle threw: "+(e&&e.stack||e))}</script>
__MDHERO_BOOT__
</body>
</html>
`;
  const outFile = path.join(OUT_DIR, "preview.html");
  fs.writeFileSync(outFile, html);
  return { outFile, bytes: Buffer.byteLength(html) };
}

function main() {
const cssChars = extractComponentStyles();
console.log(`extracted ${cssChars} chars of component CSS -> ${path.relative(ROOT, GENERATED)}`);

execFileSync("pnpm", ["exec", "vite", "build", "--config", "vite.quicklook.config.ts"], {
  cwd: ROOT,
  stdio: "inherit",
});

const { outFile, bytes } = buildHtml();
console.log(`\npreview.html: ${(bytes / 1024 / 1024).toFixed(2)} MB -> ${path.relative(ROOT, outFile)}`);
}

// Only build when run as a script; importing this file (tests) must be free of
// side effects.
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  main();
}
